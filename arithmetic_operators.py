a=5
b=2
print(+a)  # unary  positive
print(-b) # unary negetive
print(a+b) # binary addition
print(a-b) # binary subtraction
print(a*b) # binary multiplication
print(a/b) # binary division
print(a%b) # binary modulo
print(a//b) # binary Floor division  // a divided by b, rounded to the next smallest whole number
print(a**b) # Binary Exponentiation // a raised to the power of b